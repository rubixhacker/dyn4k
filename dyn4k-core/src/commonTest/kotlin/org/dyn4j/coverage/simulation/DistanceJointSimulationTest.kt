        b.setAngularDamping(0.0)
        w.addBody(b)
        var dj = DistanceJoint<Body>(g, b, g.getWorldCenter(), b.getWorldCenter())
        dj.setRestDistance(10.0)
        dj.setLimitsEnabled(1.0, 5.0)
        w.addJoint(dj)
        var v1 = g.getWorldCenter()
        var v2 = b.getWorldCenter()
        assertEquals(2.0, v1.distance(v2))
        w.step(1)
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertEquals(2.0, v1.distance(v2), 1e-5)
        dj.setLimitsEnabled(6.0, 7.0)
        w.step(1)
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertEquals(6.0, v1.distance(v2), 1e-5)
        dj.setLimitsEnabled(1.0, 3.0)
        w.step(1)
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertEquals(3.0, v1.distance(v2), 1e-5)
        dj.setLimitsEnabled(5.0, 10.0)
        dj.setLowerLimitEnabled(false)
        w.step(1)
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertEquals(3.0, v1.distance(v2), 1e-5)
        dj.setLimitsEnabled(0.0, 2.0)
        dj.setUpperLimitEnabled(false)
        w.step(1)
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertEquals(3.0, v1.distance(v2), 1e-5)
    }
