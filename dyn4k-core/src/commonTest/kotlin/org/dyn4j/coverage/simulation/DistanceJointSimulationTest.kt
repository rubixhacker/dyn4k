    @Test
    fun springWithMaxForce() {
        val w = World<Body>()
        w.setGravity(Vector2(0.0, 0.0))
        var g = Body()
        var gf = g.addFixture(Geometry.createRectangle(10.0, 0.5))
        gf.setFriction(0.0)
        g.setMass(MassType.INFINITE)
        g.setLinearDamping(0.0)
        g.setAngularDamping(0.0)
        w.addBody(g)
        var b = Body()
        var bf = b.addFixture(Geometry.createCircle(0.5))
        bf.setFriction(0.0)
        b.setMass(MassType.NORMAL)
        b.translate(0.0, 2.0)
        b.setLinearDamping(0.0)
        b.setAngularDamping(0.0)
        w.addBody(b)
        var dj = DistanceJoint<Body>(g, b, g.getWorldCenter(), b.getWorldCenter())
        dj.setRestDistance(3.0)
        dj.setSpringEnabled(true)
        dj.setSpringFrequency(8.0)
        dj.setSpringDamperEnabled(true)
        dj.setSpringDampingRatio(0.2)
        dj.setMaximumSpringForceEnabled(true)
        dj.setMaximumSpringForce(200.0)
        w.addJoint(dj)
        var v1 = g.getWorldCenter()
        var v2 = b.getWorldCenter()
        assertEquals(2.0, v1.distance(v2))
        w.step(1)
        var invdt = w.getTimeStep().getInverseDeltaTime()
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertTrue(v1.distance(v2) > 2.0)
        assertEquals(0.0, dj.getReactionTorque(invdt))
        assertEquals(0.0, dj.getReactionForce(invdt).x, 1e-3)
        assertEquals(-200.0, dj.getReactionForce(invdt).y, 1e-3)
        assertEquals(200.0, dj.getSpringForce(invdt), 1e-3)
        dj.setLimitsEnabled(0.0, 4.0)
        w.step(1)
        v1 = g.getWorldCenter()
        v2 = b.getWorldCenter()
        assertTrue(v1.distance(v2) > 2.0)
        assertEquals(0.0, dj.getReactionTorque(invdt))
        assertEquals(0.0, dj.getReactionForce(invdt).x, 1e-3)
        assertEquals(-200.0, dj.getReactionForce(invdt).y, 1e-3)
    }
