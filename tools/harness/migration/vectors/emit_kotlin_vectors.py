"""Emit the Kotlin vector constant from the recorded JSON. See generate_vectors.py."""
import json
from pathlib import Path

HERE = Path(__file__).resolve()
vectors = json.loads((HERE.parents[1] / "build/vectors/migration-vectors.json").read_text())
target = HERE.parents[1] / "src/jvmTest/kotlin/io/github/rubixhacker/harness/migration"
REVISION = "1cb1429545592c720451f8cb1b6f30ec169fb240"
CHUNK = 30000

text = json.dumps(vectors, indent=1, sort_keys=True) + "\n"
assert text.isascii(), "vectors must stay ASCII so the Kotlin source escapes nothing unexpected"
assert '"""' not in text
escaped = text.replace("$", "${'$'}")
chunks = [escaped[index:index + CHUNK] for index in range(0, len(escaped), CHUNK)]
parts = "\n".join(
    f'    private const val part{index}: String = """{chunk}"""'
    for index, chunk in enumerate(chunks))
appends = "\n".join(f"        append(part{index})" for index in range(len(chunks)))
body = f'''package io.github.rubixhacker.harness.migration

/**
 * Golden vectors for `tools/migration`.
 *
 * Generated by `vectors/generate_vectors.py` and `vectors/emit_kotlin_vectors.py` against the Python
 * implementation at repository revision
 * {REVISION}. The fixed-replay cases are the inputs and outputs of the Python `unittest` suite
 * itself. Do not edit by hand: regenerate with those two scripts.
 */
internal object MigrationVectors {{
{parts}

    val json: String = buildString({{
{appends}
    }})
}}
'''
(target / "MigrationVectors.kt").write_text(body)
print("MigrationVectors", len(body), len(chunks), "chunks")
