#!/usr/bin/env python3
"""Regenerate `CollectionVectors.kt` and the recorded collection fixtures.

Provenance
----------
Every expected value is produced by the Python reference, `tools/qualification/collection.py`, at
the git revision recorded in the emitted file (`REVISION`). Nothing was computed by the Kotlin port
and copied back.

What is recorded
----------------
* `artifact_route` for every name form the workflows upload, plus its rejections.
* `_keys` / `_positive` / `_inventory_digest` / `unsigned_inputs` / `candidate_lane_input` /
  `qualify.target_binary_hashes` over fixed inputs.
* A complete empty collection at the candidate revision: `collection.json`,
  `assembly-inputs.json`, and `candidate-manifest-inputs.json`, written next to this generator's
  resource directory so the Kotlin suite can compare the bytes.

Output
------
    python3 tools/harness/qualification/parity/generate_collection_vectors.py
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "tools" / "qualification"))

import collection  # noqa: E402
import independent_gates  # noqa: E402
import qualify  # noqa: E402

TARGET = (
    ROOT / "tools" / "harness" / "qualification" / "src" / "jvmTest" / "kotlin" / "io" / "github"
    / "rubixhacker" / "harness" / "qualification" / "CollectionVectors.kt"
)
RESOURCES = (
    ROOT / "tools" / "harness" / "qualification" / "src" / "jvmTest" / "resources" / "collection"
)


def revision():
    return subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()


def head():
    return revision()


def kotlin(text):
    encoded = json.dumps(text, ensure_ascii=True)
    return '"' + encoded[1:-1].replace("\\/", "/").replace("$", "\\$") + '"'


def outcome(call):
    try:
        return {"ok": True, "value": call()}
    except Exception as error:  # noqa: BLE001 - the message is the recorded evidence
        return {"ok": False, "error": str(error)}


def main():
    sha = head()
    other = "0" * 40 if sha != "0" * 40 else "1" * 40
    lines = []
    def add(text=""):
        lines.append(text)
    add("// Generated by tools/harness/qualification/parity/generate_collection_vectors.py.")
    add("// Source of truth: tools/qualification/collection.py at the revision below.")
    add("package io.github.rubixhacker.harness.qualification")
    add()
    add("internal object CollectionVectors {")
    add("    const val REVISION = " + kotlin(sha))
    add("    const val OTHER_CANDIDATE = " + kotlin(other))
    add()

    # artifact_route
    names = [
        f"full-ci-{sha}",
        f"full-common-{sha}",
        f"publication-{sha}-ubuntu",
        f"publication-{sha}-macos",
        f"publication-{sha}-windows",
        f"duplicate-provider-{sha}",
        f"qualification-{sha}",
        f"qualification-full-{sha}-macosArm64",
        f"qualification-{sha}-iosSimulatorArm64",
        f"windows-failure-raw-{sha}-mingwX64",
        f"full-ci-{other}",
        f"qualification-full-{other}-macosArm64",
        f"full-ci-{'f' * 40}",
        "plain-name",
        f"full-ci-{sha}-extra",
    ]
    add("    /** `artifact_route` for every uploaded name form and its rejections. */")
    add("    class Route(val name: String, val route: String?, val error: String?)")
    add()
    add("    val ROUTES = listOf(")
    for name in names:
        result = outcome(lambda: collection.artifact_route(name, sha))
        add(
            "        Route(" + kotlin(name) + ", "
            + (kotlin(result["value"]) if result["ok"] else "null") + ", "
            + ("null" if result["ok"] else kotlin(result["error"])) + "),"
        )
    add("    )")
    add()

    # _keys / _positive
    add("    /** `_keys` accept and reject cases. */")
    add("    class KeysCase(val value: String, val required: List<String>, val optional: List<String>, val error: String?)")
    add()
    key_cases = [
        ({"a": 1}, ["a"], []),
        ({"a": 1, "b": 2}, ["a"], ["b"]),
        ({"a": 1, "c": 2}, ["a"], ["b"]),
        ({"b": 1}, ["a"], []),
        ([], ["a"], []),
        ({"a": 1}, ["a", "b"], []),
    ]
    add("    val KEYS = listOf(")
    for value, required, optional in key_cases:
        error = outcome(lambda: collection._keys(value, tuple(required), tuple(optional)))
        add(
            "        KeysCase(" + kotlin(json.dumps(value, sort_keys=True)) + ", "
            + "listOf(" + ", ".join(kotlin(item) for item in required) + "), "
            + "listOf(" + ", ".join(kotlin(item) for item in optional) + "), "
            + ("null" if error["ok"] else kotlin(error["error"])) + "),"
        )
    add("    )")
    add()
    add("    /** `_positive` accept and reject cases. */")
    positives = [1, 0, -1, 1.0, "1", True, None, 112]
    add("    val POSITIVE = listOf(")
    for value in positives:
        add(
            "        " + kotlin(json.dumps(value)) + " to "
            + ("true" if collection._positive(value) else "false") + ","
        )
    add("    )")
    add()

    # _inventory_digest + a recorded inventory
    inventory = {
        "a.txt": {"size": 3, "sha256": "a" * 64},
        "dir/b.txt": {"size": 5, "sha256": "b" * 64},
    }
    add("    const val INVENTORY = " + kotlin(json.dumps(inventory, sort_keys=True)))
    add("    const val INVENTORY_DIGEST = " + kotlin(collection._inventory_digest(inventory)))
    add()

    # unsigned_inputs + candidate lane inputs + target hashes
    manifest = independent_gates.load_approved_manifest(ROOT)
    artifacts = [(f"duplicate-provider-{sha}", "/tmp/producers/duplicate-provider")]
    rows = [{"name": artifacts[0][0], "route": "duplicate-provider"}]
    add("    /** `unsigned_inputs` for one retained duplicate-provider artifact. */")
    add("    const val UNSIGNED_INPUTS = " + kotlin(json.dumps(
        collection.unsigned_inputs(manifest, artifacts, rows), sort_keys=True)))
    add("    const val UNSIGNED_INPUTS_EMPTY = " + kotlin(json.dumps(
        collection.unsigned_inputs(manifest, [], []), sort_keys=True)))
    add()
    audit = {"candidate_sha": sha, "status": "PASSED", "artifacts": [
        {"path": qualify.target_binary_path(module, target),
         "sha256": (f"{index + 1}" * 64)[:64]}
        for index, (target, module) in enumerate(
            (target, module)
            for target in ("jvm", "linuxX64")
            for module in qualify.MODULES)
    ]}
    hashes = qualify.target_binary_hashes(audit["artifacts"])
    add("    /** `qualify.target_binary_hashes` over a two-target audit. */")
    add("    const val TARGET_HASHES = " + kotlin(json.dumps(hashes, sort_keys=True)))
    add()

    # the empty collection documents
    RESOURCES.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary) / "collection"
        collection.collect(ROOT, sha, [], output)
        for name in ("collection.json", "assembly-inputs.json", "candidate-manifest-inputs.json"):
            (RESOURCES / f"empty-{name}").write_bytes((output / name).read_bytes())
    add("    const val SOURCE_TREE = " + kotlin(collection.source_tree(ROOT, sha)))
    add("}")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET} at {sha}")
    print(f"wrote {RESOURCES}/empty-*.json")


if __name__ == "__main__":
    main()
