#!/usr/bin/env python3
"""Regenerate `QualifyVectors.kt` for the qualification ports.

Every expected value is produced by the Python reference at the git revision recorded in the
emitted file. Recorded here: `full_hosted_lane` over a synthetic verified receipt (accept, plus the
runtime/configuration/case-count mutations), and the `matrix` action's printed document.

    python3 tools/harness/qualification/parity/generate_qualify_vectors.py
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "tools" / "qualification"))
import qualify  # noqa: E402

TARGET = (ROOT / "tools/harness/qualification/src/jvmTest/kotlin/io/github/rubixhacker/harness"
          / "qualification/QualifyVectors.kt")


def revision():
    return subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()


def kotlin(text):
    encoded = json.dumps(text, ensure_ascii=True)
    return '"' + encoded[1:-1].replace("\\/", "/").replace("$", "\\$") + '"'


def outcome(call):
    try:
        return json.dumps(call(), sort_keys=False), None
    except Exception as error:  # noqa: BLE001 - the message is recorded evidence
        return None, str(error)


def receipt(target="macosArm64"):
    cases = lambda prefix: [f"{prefix}case{index}" for index in range(2465 if prefix == "core" else 58)]
    configs = []
    for configuration in ("debug-g", "optimized-opt"):
        configs.append({
            "configuration": configuration,
            "source": [
                {"module": "dyn4k-core", "case_ids": cases("core")},
                {"module": "dyn4k", "case_ids": cases("facade")},
            ],
            "consumer": {"case_ids": ["a", "b", "c"]},
        })
    return {
        "target": target,
        "runtime": {"system": "Darwin", "machine": "arm64", "os_version": "26.6.2"},
        "runner_os": "macOS", "runner_arch": "ARM64", "runner_name": "runner-1",
        "configurations": configs,
        "manifest_sha256": "a" * 64, "source_tree_sha256": "b" * 64,
        "map_sha256": "c" * 64, "reviewed_pairs_sha256": "d" * 64,
        "artifact_hashes": {"dyn4k-core": "e" * 64, "dyn4k": "f" * 64},
    }


def main():
    lines = []
    def add(text=""):
        lines.append(text)
    add("// Generated by tools/harness/qualification/parity/generate_qualify_vectors.py.")
    add("package io.github.rubixhacker.harness.qualification")
    add()
    add("internal object QualifyVectors {")
    add("    const val REVISION = " + kotlin(revision()))
    add()
    add("    /** `full_hosted_lane` cases: the receipt, the lane value or the reference message. */")
    add("    class LaneCase(val label: String, val receipt: String, val lane: String?, val error: String?)")
    add()
    add("    val LANE_CASES = listOf(")
    base = receipt()
    mutations = [
        ("accepted", base),
        ("windows runtime", {**base, "target": "mingwX64"}),
        ("safari runtime", {**base, "target": "jsSafari",
                            "runtime": {**base["runtime"], "safari_version": ""}}),
        ("missing runtime version", {**base, "runtime": {"system": "Darwin", "machine": "arm64"}}),
        ("one configuration", {**base, "configurations": base["configurations"][:1]}),
        ("short consumer", {**base, "configurations": [
            {**config, "consumer": {"case_ids": ["a", "b"]}}
            for config in base["configurations"]]}),
        ("short core", {**base, "configurations": [
            {**config, "source": [config["source"][0], config["source"][1]]}
            for config in base["configurations"]]}),
    ]
    for label, value in mutations:
        lane, error = outcome(lambda: qualify.full_hosted_lane(value, "9" * 64))
        add(
            "        LaneCase(" + kotlin(label) + ", " + kotlin(json.dumps(value, sort_keys=True))
            + ", " + (kotlin(lane) if lane else "null") + ", "
            + (kotlin(error) if error else "null") + "),"
        )
    add("    )")
    add()
    add("    /** The `matrix` action document. */")
    add("    const val MATRIX = " + kotlin(json.dumps(qualify.expand(qualify.matrix()), indent=2)))
    add("}")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET} at {revision()}")


if __name__ == "__main__":
    main()
