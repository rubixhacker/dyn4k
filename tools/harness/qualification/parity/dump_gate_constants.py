#!/usr/bin/env python3
"""Generates `GateConstants.kt` from the reference `independent_gates.py`.

The reference verifier selects which approved checker and producer blob closure applies to a
candidate from about three thousand recorded path/digest pairs. Those tables are data, not
behaviour, so the port carries them as generated Kotlin constants rather than as a hand copy.

Usage (from the repository root):

    python3 tools/harness/qualification/parity/dump_gate_constants.py \
        > tools/harness/qualification/src/jvmMain/kotlin/io/github/rubixhacker/harness/qualification/GateConstants.kt

The revision named in the generated header is the commit the generator read the reference from.
"""
import re
import subprocess
import sys
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[4]
QUALIFICATION = REPOSITORY / "tools" / "qualification"

# Constants the ported Kotlin declares by hand, so that each has one reviewed source.
HAND_WRITTEN = frozenset({
    "LANE_GATES",
    "GLOBAL_GATES",
    "PRODUCER_SCOPED_GATES",
    "PRODUCER_MANIFEST_PATHS",
    "APPROVED_POLICY",
    "APPROVED_COMPARATOR_REVISIONS",
    "HISTORICAL_COMPARATOR_SHA256",
    "HISTORICAL_FIXTURE_SHA256",
    "CURRENT_FIXTURE_REVISION",
    "PROSPECTIVE_POLICY_REVISION",
    "PROSPECTIVE_POLICY_SHA256",
    "PROSPECTIVE_PREVIOUS_POLICY_REVISION",
    "PROSPECTIVE_PREVIOUS_POLICY_SHA256",
    "PROSPECTIVE_HISTORICAL_POLICY_REVISION",
    "PROSPECTIVE_HISTORICAL_POLICY_SHA256",
    "PROSPECTIVE_POLICY_PATH",
    "PROSPECTIVE_CASE_COUNT",
    "JOINT_PHYSICAL_CASES",
    "JOINT_PHYSICAL_STEPS",
})

NAME = re.compile(r"\A[A-Z][A-Z0-9_]*\Z")


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entries(pairs, indent):
    pad = " " * indent
    return "".join(
        f"{pad}{literal(key)} to {literal(value)},\n" for key, value in pairs
    )


def render(name, value):
    if isinstance(value, bool):
        raise TypeError(f"{name}: booleans are not part of the reference tables")
    if isinstance(value, int):
        return f"    const val {name} = {value}\n"
    if isinstance(value, str):
        return f"    const val {name} = {literal(value)}\n"
    if isinstance(value, (tuple, list, frozenset)):
        if not all(isinstance(item, str) for item in value):
            raise TypeError(f"{name}: sequence entry is not a string")
        body = "".join(f"        {literal(item)},\n" for item in value)
        return f"    val {name}: List<String> = listOf(\n{body}    )\n"
    if isinstance(value, dict):
        kinds = {type(item) for item in value.values()}
        if kinds == {str}:
            body = entries(value.items(), 8)
            return (
                f"    val {name}: Map<String, String> = linkedMapOf(\n{body}    )\n"
            )
        if kinds == {tuple} and all(
            isinstance(item, str) for entry in value.values() for item in entry
        ):
            body = ""
            for key, entry in value.items():
                inner = "".join(f"            {literal(item)},\n" for item in entry)
                body += f"        {literal(key)} to listOf(\n{inner}        ),\n"
            return (
                f"    val {name}: Map<String, List<String>> = linkedMapOf(\n{body}    )\n"
            )
        raise TypeError(f"{name}: unsupported table value types {kinds}")
    raise TypeError(f"{name}: unsupported table type {type(value)}")


def main():
    sys.path.insert(0, str(QUALIFICATION))
    import independent_gates as reference

    revision = subprocess.check_output(
        ["git", "-C", str(REPOSITORY), "rev-parse", "HEAD"], text=True
    ).strip()
    sys.stdout.write(
        "// Generated by tools/harness/qualification/parity/dump_gate_constants.py from\n"
        f"// tools/qualification/independent_gates.py at revision {revision}.\n"
        "// Do not edit: rerun the generator instead.\n"
        "package io.github.rubixhacker.harness.qualification\n\n"
        "/** The recorded approved blob tables of `independent_gates.py`. */\n"
        "object GateConstants {\n"
    )
    for name in sorted(dir(reference)):
        if not NAME.match(name) or name in HAND_WRITTEN:
            continue
        value = getattr(reference, name)
        if value is None or hasattr(value, "pattern") or hasattr(value, "__name__"):
            continue
        sys.stdout.write(render(name, value))
    sys.stdout.write("}\n")


if __name__ == "__main__":
    main()
