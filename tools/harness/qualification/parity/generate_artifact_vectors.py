#!/usr/bin/env python3
"""Regenerate `ArtifactVectors.kt` and the recorded artifact fixtures.

Provenance
----------
Every expected value here is produced by the Python reference,
`tools/qualification/artifact.py`, at the git revision recorded in the emitted file
(`REVISION`). Nothing was computed by the Kotlin port and copied back.

What is recorded
----------------
* `capture_staging` over `publication/valid.zip` (the recorded staging tree the Kotlin
  `StagedPublicationAudit` suite already replays): the GAV list, the bundled file inventory, the
  per-target binary hashes, and the audited content contract.
* A complete `jsSafari` hosted input tree, zipped to
  `src/jvmTest/resources/publication/artifact-hosted-source.zip`: the same staging tree plus the
  three frozen consumer cases, the hosted probe and its consumer sidecar, and the runtime matrix.
  Every report gets a fixed modification time, so the bundle `stage_hosted` produces is
  deterministic and `verification.json` can be compared byte for byte.
* The reference's own `verification.json` for that tree, plus the `verify_bundle` verdict.
* `check_ubuntu_runtime` accept/reject cases and the `UBUNTU_PROBES` group mapping.

Output
------
    python3 tools/harness/qualification/parity/generate_artifact_vectors.py
"""
import json
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "tools" / "qualification"))

import artifact  # noqa: E402
import hosted  # noqa: E402
import qualify  # noqa: E402

RESOURCES = (
    ROOT / "tools" / "harness" / "qualification" / "src" / "jvmTest" / "resources" / "publication"
)
TARGET = (
    ROOT / "tools" / "harness" / "qualification" / "src" / "jvmTest" / "kotlin" / "io" / "github"
    / "rubixhacker" / "harness" / "qualification" / "ArtifactVectors.kt"
)
CANDIDATE = "a" * 40
STAGED_TARGETS = ("jvm", "js")
HOSTED_TARGET = "jsSafari"
#: The fixed report window the hosted fixture is recorded against.
STARTED_NS = 1_700_000_000_000_000_000
FINISHED_NS = 1_700_000_100_000_000_000
XML_MTIME_NS = 1_700_000_050_000_000_000

RUNTIME = {
    "system": "Darwin",
    "machine": "arm64",
    "os_version": "26.6.2",
    "runner_image_os": "",
    "runner_image_version": "",
    "java_version": "21.0.5",
    "xcode_version": "26.5",
    "xcode_build": "Build version 17F42",
    "simulators": {},
    "safari_version": "26.6.2",
    "safaridriver_version": "SafariDriver 26.6.2",
}


def revision():
    return subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()


def kotlin(text):
    encoded = json.dumps(text, ensure_ascii=True)
    return '"' + encoded[1:-1].replace("\\/", "/").replace("$", "\\$") + '"'


def unzip(archive, destination):
    with zipfile.ZipFile(archive) as source:
        for entry in source.namelist():
            target = destination / entry
            if entry.endswith("/"):
                target.mkdir(parents=True, exist_ok=True)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with source.open(entry) as stream, target.open("wb") as output:
                shutil.copyfileobj(stream, output)


def set_mtime(path, value=XML_MTIME_NS):
    import os
    os.utime(path, ns=(value, value))


def write_suite(path, cases):
    suite = ET.Element("testsuite", tests=str(len(cases)), failures="0", errors="0",
                       skipped="0", time="0.1")
    for classname, name in cases:
        ET.SubElement(suite, "testcase", classname=classname, name=name, time="0.1")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(ET.tostring(suite))
    set_mtime(path)


def main():
    manifest = qualify.load_json_strict(ROOT / "tools/qualification/foundation-probes.json")
    groups = {group["id"]: group for group in manifest["groups"]}
    lines = []

    def add(text=""):
        lines.append(text)

    add("// Generated by tools/harness/qualification/parity/generate_artifact_vectors.py.")
    add("// Source of truth: tools/qualification/artifact.py at the revision below.")
    add("package io.github.rubixhacker.harness.qualification")
    add()
    add("internal object ArtifactVectors {")
    add("    const val REVISION = " + kotlin(revision()))
    add("    const val CANDIDATE = " + kotlin(CANDIDATE))
    add("    const val HOSTED_TARGET = " + kotlin(HOSTED_TARGET))
    add("    const val STARTED_NS = " + str(STARTED_NS))
    add("    const val FINISHED_NS = " + str(FINISHED_NS))
    add("    const val XML_MTIME_NS = " + str(XML_MTIME_NS))
    add("    const val SOURCE_FIXTURE = " + kotlin("artifact-hosted-source.zip"))
    add()

    # ------------------------------------------------------------------------------------
    # capture_staging
    # ------------------------------------------------------------------------------------
    with tempfile.TemporaryDirectory() as temporary:
        root = Path(temporary)
        repository = root / "repository"
        repository.mkdir()
        unzip(RESOURCES / "valid.zip", repository)
        destination = root / "capture"
        destination.mkdir()
        gav, files, hashes, contract = artifact.capture_staging(
            repository, destination, STAGED_TARGETS, CANDIDATE)

        add("    /** `capture_staging` over the recorded staging fixture, for `jvm` and `js`. */")
        add("    class Capture(")
        add("        val gav: List<String>,")
        add("        val files: List<Pair<String, String>>,")
        add("        val hashes: Map<String, Map<String, String>>,")
        add("        val contract: String,")
        add("    )")
        add()
        add("    val CAPTURE = Capture(")
        add("        gav = listOf(" + ", ".join(kotlin(item) for item in gav) + "),")
        add("        files = listOf(")
        for item in files:
            add("            " + kotlin(item["path"]) + " to " + kotlin(item["sha256"]) + ",")
        add("        ),")
        add("        hashes = mapOf(")
        for target in STAGED_TARGETS:
            add(
                "            " + kotlin(target) + " to mapOf("
                + ", ".join(
                    kotlin(module) + " to " + kotlin(hashes[target][module])
                    for module in qualify.MODULES
                ) + "),"
            )
        add("        ),")
        add("        contract = " + kotlin(json.dumps(contract, sort_keys=True)) + ",")
        add("    )")
        add()

        # --------------------------------------------------------------------------------
        # A complete jsSafari hosted input tree
        # --------------------------------------------------------------------------------
        consumer = groups[f"consumer-{HOSTED_TARGET}"]
        cases = qualify.expected_probe_cases(manifest, consumer)
        by_class = {}
        for classname, name in cases:
            by_class.setdefault(classname, []).append(name)
        for classname, names in by_class.items():
            write_suite(
                repository / f"consumers/qualification/portable/build/test-results/"
                f"jsBrowserTest/TEST-{classname}.xml",
                [(classname, name) for name in names],
            )

        count = len(cases)
        summary = {"id": f"consumer-{HOSTED_TARGET}", "expected": count, "executed": count,
                   "reported": count, "failures": 0, "errors": 0, "skipped": 0}
        probe = {"candidate_sha": CANDIDATE, "status": "PROBE_PASSED",
                 "manifest_sha256": qualify.manifest_digest(
                     {**manifest, "groups": [consumer]}),
                 "expected": count, "executed": count, "reported": count,
                 "groups": [summary], "failures": 0, "errors": 0, "skipped": 0,
                 "exit_code": 0, "started_at_ns": STARTED_NS, "finished_at_ns": FINISHED_NS}
        hashes_js = hosted.target_hashes(repository / "build/staging-repository", "js")
        hosted_probe = {"candidate_sha": CANDIDATE, "target": HOSTED_TARGET,
                        "status": "PROBE_PASSED", "runtime": RUNTIME,
                        "consumer_probe": probe, "artifact_hashes": hashes_js}
        lanes = [{"id": case["id"], "status": "NOT_RUN", "reason": "no evidence supplied"}
                 for case in qualify.expand(qualify.matrix())]
        matrix = {"candidate_sha": CANDIDATE, "total": len(lanes),
                  "bounded_hosted_probes": [hosted_probe], "lanes": lanes,
                  "counts": {"PASSED": 0, "FAILED": 0, "UNAVAILABLE": 0, "NOT_RUN": len(lanes)}}
        probe_path = repository / f"hosted-{HOSTED_TARGET}.json"
        probe_path.write_text(json.dumps(hosted_probe))
        probe_path.with_name(probe_path.stem + "-consumer.json").write_text(json.dumps(probe))
        (repository / f"matrix-{HOSTED_TARGET}.json").write_text(json.dumps(matrix))

        bundle = root / "bundle"
        result = artifact.stage_hosted(repository, manifest, CANDIDATE, HOSTED_TARGET,
                                       probe_path, repository / f"matrix-{HOSTED_TARGET}.json",
                                       bundle)
        verification = (bundle / "verification.json").read_text()
        verified = artifact.verify_bundle(bundle, manifest, CANDIDATE)
        verified_without_matrix = None
        (bundle / f"json/matrix-{HOSTED_TARGET}.json").unlink()
        try:
            artifact.verify_bundle(bundle, manifest, CANDIDATE)
        except ValueError as error:
            verified_without_matrix = str(error)
        (bundle / f"json/matrix-{HOSTED_TARGET}.json").write_text(json.dumps(matrix))

        add("    /** The reference `stage_hosted` result over the recorded input tree. */")
        add("    class Staged(")
        add("        val status: String,")
        add("        val executed: Int,")
        add("        val expected: Int,")
        add("        val reported: Int,")
        add("        val groups: Map<String, Int>,")
        add("        val reportedGroups: Map<String, Int>,")
        add("        val gav: List<String>,")
        add("        val verificationJson: String,")
        add("    )")
        add()
        add("    val STAGED = Staged(")
        add("        status = " + kotlin(result["status"]) + ",")
        add("        executed = " + str(result["executed"]) + ",")
        add("        expected = " + str(result["expected"]) + ",")
        add("        reported = " + str(result["reported"]) + ",")
        add(
            "        groups = mapOf("
            + ", ".join(kotlin(k) + " to " + str(v) for k, v in result["groups"].items()) + "),"
        )
        add(
            "        reportedGroups = mapOf("
            + ", ".join(kotlin(k) + " to " + str(v)
                        for k, v in result["reported_groups"].items()) + "),"
        )
        add("        gav = listOf(" + ", ".join(kotlin(item) for item in result["gav"]) + "),")
        add("        verificationJson = " + kotlin(verification) + ",")
        add("    )")
        add()
        add("    /** `verify_bundle` over the reference bundle. */")
        add("    val VERIFIED_EXECUTED = " + str(verified["executed"]))
        add("    val VERIFIED_WITHOUT_MATRIX = " + kotlin(verified_without_matrix or ""))
        add()

        # The zipped input tree, without the produced bundle.
        source_zip = RESOURCES / "artifact-hosted-source.zip"
        with zipfile.ZipFile(source_zip, "w", zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(repository.rglob("*")):
                if not path.is_file():
                    continue
                archive.write(path, path.relative_to(repository).as_posix())

    # ------------------------------------------------------------------------------------
    # check_ubuntu_runtime
    # ------------------------------------------------------------------------------------
    UBUNTU = {"system": "Linux", "machine": "x86_64", "kernel_release": "6.8.0",
              "distribution": "ubuntu", "os_version": "24.04", "runner_image_os": "ubuntu24",
              "runner_image_version": "20250801.1.0", "github_actions": True,
              "java_version": "21.0.8"}
    CASES = [
        ("runner image", UBUNTU),
        ("local host", {**UBUNTU, "github_actions": False, "runner_image_os": "",
                        "runner_image_version": ""}),
        ("not linux", {**UBUNTU, "system": "Darwin"}),
        ("wrong machine", {**UBUNTU, "machine": "arm64"}),
        ("amd64 spelling", {**UBUNTU, "machine": "AMD64"}),
        ("missing distribution", {**UBUNTU, "distribution": ""}),
        ("missing version", {**UBUNTU, "os_version": ""}),
        ("missing kernel", {**UBUNTU, "kernel_release": ""}),
        ("missing java", {**UBUNTU, "java_version": ""}),
        ("missing runner image", {**UBUNTU, "runner_image_os": ""}),
        ("missing runner version", {**UBUNTU, "runner_image_version": ""}),
        ("non ubuntu image", {**UBUNTU, "distribution": "debian"}),
    ]
    add("    /** `check_ubuntu_runtime` accept and reject cases. */")
    add("    class RuntimeCase(val label: String, val runtime: String, val error: String?)")
    add()
    add("    val UBUNTU_RUNTIME_CASES = listOf(")
    for label, runtime in CASES:
        try:
            artifact.check_ubuntu_runtime(runtime)
            error = None
        except ValueError as failure:
            error = str(failure)
        add(
            "        RuntimeCase(" + kotlin(label) + ", "
            + kotlin(json.dumps(runtime, sort_keys=True)) + ", "
            + ("null" if error is None else kotlin(error)) + "),"
        )
    add("    )")
    add()
    add("    val UBUNTU_PROBES = mapOf(")
    for name, ids in artifact.UBUNTU_PROBES.items():
        add(
            "        " + kotlin(name) + " to listOf("
            + ", ".join(kotlin(item) for item in ids) + "),"
        )
    add("    )")
    add("}")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET} at {revision()}")
    print(f"wrote {RESOURCES / 'artifact-hosted-source.zip'}")


if __name__ == "__main__":
    main()
