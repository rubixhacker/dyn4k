#!/usr/bin/env python3
"""Regenerate `FullAdapterVectors.kt` from the three shared adapter modules.

Records the tables the Kotlin adapters must reproduce: the Android route table, the browser lane,
Chromium, toolchain-key and artifact tables, and the KLIB lane and key tables, each read from the
Python implementation at the recorded revision.

    python3 tools/harness/qualification/parity/generate_full_adapter_vectors.py
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "tools" / "qualification"))
import full_android_adapter as android  # noqa: E402
import full_android_consumer  # noqa: E402
import full_browser_adapter as browser  # noqa: E402
import full_browser_consumer  # noqa: E402
import full_klib_adapter as klib  # noqa: E402
import full_klib_consumer  # noqa: E402

TARGET = (ROOT / "tools/harness/qualification/src/jvmTest/kotlin/io/github/rubixhacker/harness"
          / "qualification/FullAdapterVectors.kt")


def revision():
    return subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()


def kotlin(text):
    encoded = json.dumps(text, ensure_ascii=True)
    return '"' + encoded[1:-1].replace("\\/", "/").replace("$", "\\$") + '"'


def main():
    lines = []
    def add(text=""):
        lines.append(text)
    add("// Generated by tools/harness/qualification/parity/generate_full_adapter_vectors.py.")
    add("package io.github.rubixhacker.harness.qualification")
    add()
    add("internal object FullAdapterVectors {")
    add("    const val REVISION = " + kotlin(revision()))
    add()
    add("    val ANDROID_MODULES = listOf("
        + ", ".join(kotlin(m) for m in full_android_consumer.MODULES) + ")")
    add("    val ANDROID_ROUTES = mapOf(")
    for lane, (api, configuration) in android.ROUTES.items():
        add("        " + kotlin(lane) + " to (" + kotlin(api) + " to " + kotlin(configuration) + "),")
    add("    )")
    add()
    add("    val BROWSER_MODULES = listOf("
        + ", ".join(kotlin(m) for m in full_browser_consumer.MODULES) + ")")
    add("    const val BROWSER_JAVA_SHA256 = " + kotlin(full_browser_consumer.JAVA_SHA256))
    add("    const val BROWSER_GRADLE_SHA256 = " + kotlin(full_browser_consumer.GRADLE_SHA256))
    add("    val BROWSER_CHROMIUM = mapOf(")
    for role, (major, digest) in full_browser_consumer.CHROMIUM.items():
        add("        " + kotlin(role) + " to (" + str(major) + " to " + kotlin(digest) + "),")
    add("    )")
    add("    val BROWSER_LANES = setOf(")
    for lane in sorted(full_browser_consumer.LANES):
        add("        " + kotlin(lane) + ",")
    add("    )")
    add("    val BROWSER_TOOLCHAIN_KEYS = setOf(")
    for key in sorted(browser.TOOLCHAIN_KEYS):
        add("        " + kotlin(key) + ",")
    add("    )")
    add()
    add("    val KLIB_MODULES = listOf("
        + ", ".join(kotlin(m) for m in full_klib_consumer.MODULES) + ")")
    add("    val KLIB_LOCAL_LANES = setOf(")
    for lane in sorted(full_klib_consumer.LOCAL_LANES):
        add("        " + kotlin(lane) + ",")
    add("    )")
    add("    val KLIB_TOOLCHAIN_KEYS = setOf(")
    for key in sorted(klib.TOOLCHAIN_KEYS):
        add("        " + kotlin(key) + ",")
    add("    )")
    add("    val KLIB_NATIVE_KEYS = setOf(")
    for key in sorted(klib.NATIVE_KEYS):
        add("        " + kotlin(key) + ",")
    add("    )")
    add("}")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET} at {revision()}")


if __name__ == "__main__":
    main()
