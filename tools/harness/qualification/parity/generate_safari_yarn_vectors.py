#!/usr/bin/env python3
"""Regenerate `SafariYarnLockVectors.kt` from `tools/qualification/safari_yarn_lock.py`.

Records the pure predicates (`hosted_task_markers`, `safari_capture_timeout`,
`safari_output_overflow`, `full_hosted_command`, `lock_failure_signature`) and the constants the
Kotlin contract must reproduce, at the git revision recorded in the file.

    python3 tools/harness/qualification/parity/generate_safari_yarn_vectors.py
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "tools" / "qualification"))
import safari_yarn_lock as s  # noqa: E402

TARGET = (ROOT / "tools/harness/qualification/src/jvmTest/kotlin/io/github/rubixhacker/harness"
          / "qualification/SafariYarnLockVectors.kt")


def revision():
    return subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()


def kotlin(text):
    encoded = json.dumps(text, ensure_ascii=True)
    return '"' + encoded[1:-1].replace("\\/", "/").replace("$", "\\$") + '"'


TIMEOUT_STDOUT = ("> Task :dyn4k-core:jsBrowserTest FAILED\n"
                  "Safari has not captured in 60000 ms, killing.\n")
TIMEOUT_STDERR = ("Safari failed 3 times (timeout). Giving up.\n"
                  "Errors occurred during launch of browser for testing.\n")
OVERFLOW_STDERR = ("##teamcity[testFailed name='overflow-message' message='x']\n"
                   "Cannot process output: too long teamcity service message "
                   "(more than 1Mb). Event was lost.\n")
LOCK_STDERR = ("FAILURE: Build failed with an exception.\n"
               "* What went wrong:\n"
               "Execution failed for task ':kotlinStoreYarnLock' (registered by plugin class "
               "'org.jetbrains.kotlin.gradle.targets.js.yarn.YarnPlugin').\n"
               "> Lock file was changed. Run the `kotlinUpgradeYarnLock` task to actualize lock file\n"
               "* Try:\n"
               "BUILD FAILED in 1m 2s\n")


# The port substitutes the Kotlin tools for the archived Python ones. The inventory formatting is
# the reference's own `hosted_expected_files`, so the vector runs it over the substituted list.
KOTLIN_HOSTED_INPUTS = [
    "tools/harness/qualification/src/jvmMain/kotlin/io/github/rubixhacker/harness/qualification"
    "/FullHosted.kt",
    "dyn4k-core/build.gradle.kts",
    "dyn4k/build.gradle.kts",
    "tools/qualification/safari-launch.sh",
    "docs/archive/hosted-macos-workflows/safari-yarn-lock-diagnostic.yml",
    "tools/harness/qualification/src/commonMain/kotlin/io/github/rubixhacker/harness/qualification"
    "/SafariReporter.kt",
    "tools/harness/qualification/src/jvmMain/kotlin/io/github/rubixhacker/harness/qualification"
    "/SafariYarnLockHost.kt",
    "tools/qualification/safari-karma-reporter.js",
]


def main():
    lines = []
    def add(text=""):
        lines.append(text)
    add("// Generated by tools/harness/qualification/parity/generate_safari_yarn_vectors.py.")
    add("package io.github.rubixhacker.harness.qualification")
    add()
    add("internal object SafariYarnLockVectors {")
    add("    const val REVISION = " + kotlin(revision()))
    add("    const val TRACKED_LOCK = " + kotlin(str(s.TRACKED_LOCK)))
    add("    const val GENERATED_LOCK = " + kotlin(str(s.GENERATED_LOCK)))
    add("    val SOURCE_INPUTS = listOf(" + ", ".join(kotlin(str(p)) for p in s.SOURCE_INPUTS) + ")")
    add("    val REQUIRED_PACKAGES = listOf(" + ", ".join(kotlin(p) for p in s.REQUIRED_PACKAGES) + ")")
    add("    val REQUIRED_PACKAGE_INPUTS = listOf("
        + ", ".join(kotlin(str(p)) for p in s.REQUIRED_PACKAGE_INPUTS) + ")")
    add("    val CONTEXT_ROOTS = listOf(" + ", ".join(kotlin(str(p)) for p in s.CONTEXT_ROOTS) + ")")
    add("    const val LOCK_ERROR_LINE = " + kotlin(s.LOCK_ERROR_LINE))
    add("    const val MAX_FILE_BYTES = " + str(s.MAX_FILE_BYTES))
    add("    const val MAX_PACKAGES = " + str(s.MAX_PACKAGES))
    add("    const val MAX_PROCESS_SECONDS = " + str(s.MAX_PROCESS_SECONDS))
    add("    const val MAX_DRAIN_SECONDS = " + str(s.MAX_DRAIN_SECONDS))
    add("    const val WINDOWS_KILL_JOB_ON_CLOSE = " + str(s.WINDOWS_KILL_JOB_ON_CLOSE))
    add("    const val WINDOWS_CREATE_SUSPENDED = " + str(s.WINDOWS_CREATE_SUSPENDED))
    add("    val HOSTED_TASK_MARKERS = listOf("
        + ", ".join(kotlin(m.decode()) for m in s.HOSTED_TASK_MARKERS) + ")")
    add("    val CONTEXT_BOUNDS = listOf(" + ", ".join(str(v) for v in (
        s.CONTEXT_MAX_FILES, s.CONTEXT_MAX_FILE_BYTES, s.CONTEXT_MAX_TOTAL_BYTES,
        s.CONTEXT_MAX_ENTRIES, s.CONTEXT_MAX_DEPTH, s.CONTEXT_MAX_SECONDS,
        s.CONTEXT_MAX_LAUNCHES, s.CONTEXT_MAX_RAW_ENTRIES, s.CONTEXT_MAX_UPLOAD_BYTES,
        s.CONTEXT_MAX_INVENTORY_BYTES)) + ")")
    add()
    add("    val MARKERS_PASSED = listOf("
        + ", ".join(kotlin(m.decode()) for m in s.hosted_task_markers({"exit_code": 0})) + ")")
    add("    val MARKERS_FAILED = listOf("
        + ", ".join(kotlin(m.decode()) for m in s.hosted_task_markers({"exit_code": 1})) + ")")
    add()
    add("    class Predicate(val label: String, val stdout: String, val stderr: String, val expected: Boolean)")
    add()
    add("    val TIMEOUT_CASES = listOf(")
    for label, stdout, stderr in (
        ("exact", TIMEOUT_STDOUT, TIMEOUT_STDERR),
        ("no kill line", TIMEOUT_STDOUT.replace("Safari has not captured in 60000 ms, killing.\n", ""), TIMEOUT_STDERR),
        ("wrong task", TIMEOUT_STDOUT.replace("dyn4k-core", "other"), TIMEOUT_STDERR),
        ("no giving-up", TIMEOUT_STDOUT, "Safari failed 3 times . Giving up.\nErrors occurred during launch of browser for testing.\n"),
        ("no launch error", TIMEOUT_STDOUT, "Safari failed 3 times (timeout). Giving up.\n"),
        ("crlf", TIMEOUT_STDOUT.replace("\n", "\r\n"), TIMEOUT_STDERR),
    ):
        add("        Predicate(" + kotlin(label) + ", " + kotlin(stdout) + ", " + kotlin(stderr)
            + ", " + ("true" if s.safari_capture_timeout(stdout.encode(), stderr.encode()) else "false") + "),")
    add("    )")
    add()
    add("    val OVERFLOW_CASES = listOf(")
    for label, stdout, stderr in (
        ("exact", TIMEOUT_STDOUT, OVERFLOW_STDERR),
        ("no teamcity", TIMEOUT_STDOUT, "Cannot process output: too long teamcity service message (more than 1Mb). Event was lost.\n"),
        ("no failure line", "", OVERFLOW_STDERR),
        ("quoted only", TIMEOUT_STDOUT, "##teamcity[testFailed name='overflow-message'\n"),
        ("other task", TIMEOUT_STDOUT.replace("jsBrowserTest", "jsNodeTest"), OVERFLOW_STDERR),
    ):
        add("        Predicate(" + kotlin(label) + ", " + kotlin(stdout) + ", " + kotlin(stderr)
            + ", " + ("true" if s.safari_output_overflow(stdout.encode(), stderr.encode()) else "false") + "),")
    add("    )")
    add()
    add("    val FULL_HOSTED_COMMANDS = listOf(")
    for configuration in ("development", "production"):
        add("        " + kotlin(configuration) + " to listOf("
            + ", ".join(kotlin(a) for a in s.full_hosted_command(
                Path("/repo"), "/tmp/qualification.init.gradle", configuration, "a" * 32)) + "),")
    add("    )")
    add()
    add("    val HOSTED_EXPECTED_FILES = listOf(")
    for configuration in ("development", "production"):
        expected = sorted(s.hosted_expected_files(
            configuration, s.TRACKED_LOCK, s.GENERATED_LOCK,
            (s.TRACKED_LOCK, *s.SOURCE_INPUTS, *(Path(p) for p in KOTLIN_HOSTED_INPUTS)),
            s.REQUIRED_PACKAGE_INPUTS))
        add("        " + kotlin(configuration) + " to setOf("
            + ", ".join(kotlin(p) for p in expected) + "),")
    add("    )")
    add()
    add("    val LOCK_SIGNATURE_CASES = listOf(")
    import tempfile
    lock_texts = {
        "exact": LOCK_STDERR,
        "unrelated failure": LOCK_STDERR.replace(
            "Execution failed for task ':kotlinStoreYarnLock' (registered by plugin class "
            "'org.jetbrains.kotlin.gradle.targets.js.yarn.YarnPlugin').",
            "Execution failed for task ':compileKotlin'."),
        "quoted phrase later": LOCK_STDERR + "* Exception is:\n> Lock file was changed. Run the "
        "`kotlinUpgradeYarnLock` task to actualize lock file\n",
        "two failures headers": LOCK_STDERR + "FAILURE: Build failed with an exception.\n",
    }
    for label, value in lock_texts.items():
        with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as handle:
            handle.write(value)
        outcome = s.lock_failure_signature(Path(handle.name))
        Path(handle.name).unlink()
        add("        Predicate(" + kotlin(label) + ", " + kotlin("") + ", " + kotlin(value)
            + ", " + ("true" if outcome else "false") + "),")
    add("    )")
    add()
    add("    val CONTEXT_LIMITS = listOf(")
    add("        " + ", ".join(kotlin(key) + " to " + str(value)
                              for key, value in context_limits()))
    add("    )")
    add()
    add("    /** One recorded `inputs` entry of a scanner run, as the reference wrote it. */")
    add("    class ContextEntry(")
    add("        val path: String,")
    add("        val status: String,")
    add("        val reason: String,")
    add("        val originalSize: Long,")
    add("        val retainedSize: Long,")
    add("        val sha256: String?,")
    add("    )")
    add()
    add("    /** The scanner invariants of one clean fixture run. */")
    add("    class ContextInventory(")
    add("        val status: String,")
    add("        val configuration: String,")
    add("        val copiedFiles: Long,")
    add("        val matchedFiles: Long,")
    add("        val entriesSeen: Long,")
    add("        val sidecars: List<ContextEntry>,")
    add("    )")
    add()
    record = context_inventory()
    add("    val CONTEXT_INVENTORY = ContextInventory(")
    add("        status = " + kotlin(record["status"]) + ",")
    add("        configuration = " + kotlin(record["configuration"]) + ",")
    add("        copiedFiles = " + str(record["copied_files"]) + ",")
    add("        matchedFiles = " + str(record["matched_files"]) + ",")
    add("        entriesSeen = " + str(record["entries_seen"]) + ",")
    add("        sidecars = listOf(")
    for entry in record["sidecars"]:
        add("            ContextEntry(" + ", ".join((
            kotlin(entry["path"]), kotlin(entry["status"]), kotlin(entry["reason"]),
            str(entry["original_size"]), str(entry["retained_size"]),
            "null" if entry["sha256"] is None else kotlin(entry["sha256"]))) + "),")
    add("        ),")
    add("    )")
    add("}")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET} at {revision()}")


def context_limits():
    """`inventory["limits"]`, in the order `capture_karma_context` writes it."""
    return (
        ("files", s.CONTEXT_MAX_FILES),
        ("file_bytes", s.CONTEXT_MAX_FILE_BYTES),
        ("total_bytes", s.CONTEXT_MAX_TOTAL_BYTES),
        ("upload_bytes", s.CONTEXT_MAX_UPLOAD_BYTES),
        ("inventory_bytes", s.CONTEXT_MAX_INVENTORY_BYTES),
        ("raw_entries", s.CONTEXT_MAX_RAW_ENTRIES),
        ("entries", s.CONTEXT_MAX_ENTRIES),
        ("depth", s.CONTEXT_MAX_DEPTH),
        ("seconds", s.CONTEXT_MAX_SECONDS),
        ("launches", s.CONTEXT_MAX_LAUNCHES),
    )


def context_inventory():
    """Run `capture_karma_context` over the reference's own fixture and keep its invariants.

    The scanned configuration bytes embed the absolute package path, so the configuration
    entries' sizes and digests differ between checkouts. The sidecars are fixed text, so their
    records, the counters, and the status are the same everywhere; those are what the vector
    records, keyed by path so the directory order does not matter.
    """
    import test_safari_yarn_lock as reference_case

    case = reference_case.SafariYarnLockTests("test_context_scanner_copies_regular_unique_config_with_inventory")
    case.setUp()
    try:
        context, package = case.context_fixture()
        case.write_valid_karma_configs()
        (package / "node_modules").symlink_to(case.root, target_is_directory=True)
        inventory = case.capture_context(context)
    finally:
        case.doCleanups()
    sidecars = sorted(
        (item for item in inventory["inputs"] if "/" not in item["path"]),
        key=lambda item: item["path"],
    )
    return {
        "status": inventory["status"],
        "configuration": inventory["configuration"],
        "copied_files": inventory["copied_files"],
        "matched_files": inventory["matched_files"],
        "entries_seen": inventory["entries_seen"],
        "sidecars": [
            {
                "path": item["path"],
                "status": item["status"],
                "reason": item["reason"],
                "original_size": item["original_size"],
                "retained_size": item["retained_size"],
                "sha256": item.get("sha256"),
            }
            for item in sidecars
        ],
    }


if __name__ == "__main__":
    main()
