"""Emit the Kotlin vector constants from the recorded JSON. See generate_vectors.py."""
import json
from pathlib import Path

HERE = Path(__file__).resolve()
vectors = json.loads((HERE.parents[1] / "build/vectors/compatibility-vectors.json").read_text())
target = HERE.parents[1] / "src/commonTest/kotlin/io/github/rubixhacker/harness/compatibility"
REVISION = "233edd085db9427e7feb19fd150d504b5d43be1b"
CHUNK = 30000

names = {
    "world_ci": "WorldCiVectors",
    "governing_seams": "GoverningSeamsVectors",
    "candidate_coverage": "CandidateCoverageVectors",
    "method_coverage": "MethodCoverageVectors",
    "java_corpus": "JavaCorpusVectors",
    "execution_probe": "ExecutionProbeVectors",
    "governing_disposition": "GoverningDispositionVectors",
    "full_ci": "FullCiVectors",
    "module_probe": "ModuleProbeVectors",
    "ledger": "LedgerVectors",
    "exception_ci": "ExceptionCiVectors",
}

for key, name in names.items():
    text = json.dumps(vectors[key], indent=1, sort_keys=True) + "\n"
    assert text.isascii(), key
    assert '"""' not in text, key
    escaped = text.replace("$", "${'$'}")
    chunks = [escaped[index:index + CHUNK] for index in range(0, len(escaped), CHUNK)]
    parts = "\n".join(
        f'    private const val part{index}: String = """{chunk}"""'
        for index, chunk in enumerate(chunks))
    appends = "\n".join(f"        append(part{index})" for index in range(len(chunks)))
    body = f'''package io.github.rubixhacker.harness.compatibility

/**
 * Golden vectors for `tools/compatibility/{key}.py`.
 *
 * Generated by `vectors/generate_vectors.py` and `vectors/emit_kotlin_vectors.py` against the
 * Python implementation at repository revision
 * {REVISION}. Do not edit by hand:
 * regenerate with those two scripts.
 */
internal object {name} {{
{parts}

    val json: String = buildString({{
{appends}
    }})
}}
'''
    (target / f"{name}.kt").write_text(body)
    print(name, len(body), len(chunks), "chunks")
