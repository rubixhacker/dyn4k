#!/usr/bin/env python3
"""Emit the Kotlin golden-vector fixture from `generate_vectors.py` output.

    python3 tools/harness/android/parity/generate_vectors.py > vectors.json
    python3 tools/harness/android/parity/emit_kotlin_vectors.py < vectors.json

Writes `src/jvmTest/kotlin/io/github/rubixhacker/harness/android/AndroidVectors.kt`.
The JSON is base64 encoded and emitted in chunks below the JVM class-file
constant-pool limit, so neither quoting nor `$` interpolation can alter the bytes.
"""

import base64
import json
import sys
from pathlib import Path

TARGET = (Path(__file__).resolve().parents[1]
          / "src/jvmTest/kotlin/io/github/rubixhacker/harness/android/AndroidVectors.kt")
CHUNK = 40000


def chunks(text, size):
    lines = text.splitlines(keepends=True)
    buffer = ""
    for line in lines:
        if buffer and len(buffer) + len(line) > size:
            yield buffer
            buffer = ""
        buffer += line
    if buffer:
        yield buffer


def main():
    text = sys.stdin.read()
    document = json.loads(text)
    revision = document["git_revision"]
    encoded = base64.b64encode(text.encode()).decode()
    escaped = [encoded[index:index + CHUNK] for index in range(0, len(encoded), CHUNK)]
    body = "\n".join(f'        "{chunk}",' for chunk in escaped)
    source = f'''package io.github.rubixhacker.harness.android

import java.util.Base64
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonObject

/**
 * Golden vectors for the Python modules under `tools/android-runtime` and
 * `tools/android-native-runtime`.
 *
 * Generated by `parity/generate_vectors.py` and `parity/emit_kotlin_vectors.py` against the Python
 * implementation at repository revision {revision}. Do not edit by hand: regenerate with those two
 * scripts.
 */
internal object AndroidVectors {{
    private val parts: List<String> = listOf(
{body}
    )

    val json: JsonObject by lazy {{
        val text = Base64.getDecoder().decode(parts.joinToString("")).decodeToString()
        Json.parseToJsonElement(text).jsonObject
    }}
}}
'''
    TARGET.write_text(source)
    print("wrote {} ({} chunks)".format(TARGET, len(escaped)))


if __name__ == "__main__":
    main()
